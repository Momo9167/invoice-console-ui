const fill = (s: string, v?: Record<string, unknown>) =>
  v ? s.replace(/\{(\w+)\}/g, (_, k) => String(v[k] ?? '')) : s;

export function translate(lang: Lang | undefined, s: string, v?: Record<string, unknown>, doc = false) {
  return fill((lang === 'my' && ((doc && DOC_MY[s]) || MY[s])) || EN[s] || s, v);
}
